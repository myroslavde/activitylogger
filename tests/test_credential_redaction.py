"""Capture-time credential redaction and concealed-clipboard handling.

Fake secrets are assembled at runtime so no literal credential sits in source.
"""

from __future__ import annotations

import time
from types import SimpleNamespace
from unittest.mock import MagicMock

import pytest

import interleaved_logger as il
from credential_redaction import redact
from tests.helpers import enable_features

JWT = "eyJhbGciOiJIUzI1NiJ9" + "." + "eyJzdWIiOiIxIn0" + "." + "abc123"
LABEL_SECRET = "password" + ": " + "fake" + "value12345"
AWS_KEY = "AKIA" + "FAKEFAKEFAKEFAKE"
GITHUB_TOKEN = "ghp_" + "0" * 36
SLACK_TOKEN = "xox" + "b-" + "1234567890-fake"
PEM_KEY = (
    "-----BEGIN RSA PRIVATE KEY-----\nMIIFAKE\n-----END RSA PRIVATE KEY-----"
)


@pytest.fixture(autouse=True)
def _reset(reset_logger_state):
    reset_logger_state()
    yield


@pytest.mark.parametrize(
    ("sample", "expected"),
    [
        (JWT, "[REDACTED:jwt]"),
        (AWS_KEY, "[REDACTED:aws_access_key]"),
        (GITHUB_TOKEN, "[REDACTED:github_token]"),
        (SLACK_TOKEN, "[REDACTED:slack_token]"),
        (PEM_KEY, "[REDACTED:pem_private_key]"),
        (LABEL_SECRET, "password: [REDACTED:labelled_secret]"),
    ],
)
def test_redact_catches_each_family(sample, expected):
    assert redact(sample) == expected


def test_redact_keeps_surrounding_text_and_redacts_each_match():
    text = f"login {JWT} then {AWS_KEY} done"
    assert redact(text) == (
        "login [REDACTED:jwt] then [REDACTED:aws_access_key] done"
    )


@pytest.mark.parametrize(
    "text",
    [
        "",
        "short",
        "Meeting notes for the Q3 roadmap review.",
        "password reset email sent to the team",
        "file.name.txt and version 1.2.3",
        "https://example.test/docs/page?id=42",
    ],
)
def test_redact_leaves_ordinary_text_unchanged(text):
    assert redact(text) == text


def test_redact_fails_closed_on_error():
    assert redact(None) == "[REDACTED:error]"
    assert redact(object()) == "[REDACTED:error]"


def test_redact_is_idempotent():
    once = redact(f"{LABEL_SECRET} and {JWT}")
    assert redact(once) == once


def _pasteboard(types, text="hello there"):
    pb = MagicMock()
    pb.changeCount.side_effect = [1, 2, 2]
    pb.types.return_value = types
    pb.stringForType_.return_value = text
    return pb


def _run_clipboard_loop(monkeypatch, pb):
    waits = iter([False, True])
    monkeypatch.setattr(il, "AX_AVAILABLE", True)
    monkeypatch.setattr(
        il, "NSPasteboard", SimpleNamespace(generalPasteboard=lambda: pb)
    )
    monkeypatch.setattr(il, "_capture_context", lambda *_a, **_k: (1, "App", "Win"))
    monkeypatch.setattr(il, "_capture_context_matches_locked", lambda _ctx: True)
    monkeypatch.setattr(il._stop_event, "wait", lambda _delay: next(waits))
    il.clipboard_checker_loop()


@pytest.mark.parametrize(
    "concealed_type",
    [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ],
)
def test_concealed_clipboard_never_reads_text(monkeypatch, concealed_type):
    pb = _pasteboard(["public.utf8-plain-text", concealed_type], text=LABEL_SECRET)
    _run_clipboard_loop(monkeypatch, pb)
    pb.stringForType_.assert_not_called()
    expected = f"> [CLIPBOARD]:\n{il.format_markdown_fenced_text('[concealed]')}"
    assert [str(e) for e in il._current_events] == [expected]
    assert il._current_events[0].payload == "[concealed]"
    assert LABEL_SECRET not in str(il._current_events[0])


def test_normal_clipboard_text_is_still_recorded(monkeypatch):
    pb = _pasteboard(["public.utf8-plain-text"], text="hello there")
    _run_clipboard_loop(monkeypatch, pb)
    pb.stringForType_.assert_called_once()
    assert [e.payload for e in il._current_events] == ["hello there"]
    assert il._current_events[0].kind == "clipboard"


def test_typed_secret_is_written_redacted(tmp_path):
    enable_features(tmp_path, capture_triggers_enabled=True)
    with il._lock:
        il._current_keystrokes[:] = list(f"user {LABEL_SECRET} ok")
        il._flush_keys(cause="test")
    il.flush_to_file()
    text = next((tmp_path / "logs").glob("daily_log_*.md")).read_text(encoding="utf-8")
    assert "fakevalue12345" not in text
    assert "[REDACTED:labelled_secret]" in text


def test_clipboard_secret_and_window_title_are_written_redacted(tmp_path):
    enable_features(tmp_path, capture_triggers_enabled=True)
    _, _, event = il._apply_clipboard_change_digest(2, f"token {JWT}", False, 1, "")
    assert event is not None
    il.record_clipboard_event(event)
    with il._lock:
        il._current_heading = f"Notes - {AWS_KEY}"
    il.add_event("plain follow-up")
    il.flush_to_file()
    text = next((tmp_path / "logs").glob("daily_log_*.md")).read_text(encoding="utf-8")
    assert JWT not in text
    assert AWS_KEY not in text
    assert "[REDACTED:jwt]" in text
    assert "[REDACTED:aws_access_key]" in text


def test_clipboard_change_mid_read_is_not_recorded(monkeypatch):
    pb = _pasteboard(["public.utf8-plain-text"], text="half read")
    pb.changeCount.side_effect = [1, 2, 3]
    _run_clipboard_loop(monkeypatch, pb)
    assert il._current_events == []
    assert il._last_clipboard_count == 1


def test_clipboard_concealed_after_read_is_recorded_as_placeholder(monkeypatch):
    pb = _pasteboard(["public.utf8-plain-text"], text=LABEL_SECRET)
    pb.types.side_effect = [
        ["public.utf8-plain-text"],
        ["org.nspasteboard.ConcealedType"],
    ]
    _run_clipboard_loop(monkeypatch, pb)
    assert [e.payload for e in il._current_events] == ["[concealed]"]
    assert "fakevalue" not in str(il._current_events[0])


def test_clipboard_secret_straddling_2000_chars_is_redacted_before_slice(tmp_path):
    enable_features(tmp_path)
    text = "a" * 1990 + " " + LABEL_SECRET + " tail"
    _, _, event = il._apply_clipboard_change_digest(2, text, False, 1, "")
    assert event is not None
    assert "fakevalue" not in event.payload
    assert "fakevalue" not in str(event)


def test_prose_with_password_word_is_unchanged():
    text = "password requirements for staff are in the handbook"
    assert redact(text) == text


def test_labelled_secret_requires_colon_or_equals():
    assert redact("api_key=" + "fake" + "value12345") == "api_key=[REDACTED:labelled_secret]"
    assert redact("password fake" + "value12345") == "password fake" + "value12345"


@pytest.mark.parametrize(
    "text",
    [
        "password" + " " * 8000,
        "password" + " " * 8000 + "x",
        "-----BEGIN RSA PRIVATE KEY-----\n" * 2000,
        ("-----BEGIN RSA PRIVATE KEY-----\n" + "A" * 20 + " ") * 500,
        "eyJhbGciOiJIUzI1NiJ9." * 500,
    ],
)
def test_pathological_inputs_finish_fast(text):
    start = time.perf_counter()
    redact(text)
    assert time.perf_counter() - start < 0.05


def test_multiple_pem_blocks_are_each_redacted():
    block = PEM_KEY + " and "
    assert redact(block * 3) == "[REDACTED:pem_private_key] and " * 3
